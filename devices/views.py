from .serializers import DeviceSerializer, TelemetrySerializer, AlertSerializer, DeviceLatestSerializer
from .models import Device, Telemetry, Alert
from rest_framework import viewsets
from rest_framework.mixins import CreateModelMixin, ListModelMixin
from rest_framework.decorators import action
from rest_framework.response import Response
from rest_framework.exceptions import ValidationError
from django.utils.dateparse import parse_datetime
from .pagination import StandardCursorPagination, TelemetryCursorPagination
from .services import process_telemetry

# ViewSet for devices.Provides full CRUD (list, create, retrieve, update, delete).
# Custom actions: latest, telemetry
class DeviceViewSet(viewsets.ModelViewSet):
    serializer_class = DeviceSerializer
    queryset = Device.objects.all()
    pagination_class = StandardCursorPagination

    # latest: returns the most recent telemetry for a device
    @action(detail=True, methods=["get"])
    def latest(self, request, pk=None):
        device = self.get_object()
        telemetry = device.telemetries.select_related("device").order_by("-timestamp").first()
        if telemetry is None:
            return Response(status=404)
        else:
            return Response(DeviceLatestSerializer(telemetry).data)
        
    # telemetry: returns telemetry history filtered by ?from=&to= (paginated)
    @action(detail=True, methods=["get"])
    def telemetry(self, request, pk=None):
        device = self.get_object()
        from_param = self.request.query_params.get("from")
        to_param = self.request.query_params.get("to")
        if from_param is None or to_param is None:
            raise ValidationError("'from' and 'to' are required")
        else:
            telemetry = device.telemetries.filter(timestamp__gte=parse_datetime(from_param), timestamp__lte=parse_datetime(to_param))
            self.pagination_class = TelemetryCursorPagination
            page = self.paginate_queryset(telemetry)
            serializer = TelemetrySerializer(page, many=True)
            return self.get_paginated_response(serializer.data)

# Only 'create' (POST) and 'list' (GET) are enabled.
# Delegates validation to serializer; business logic to services.      
class TelemetryViewSet(CreateModelMixin, ListModelMixin, viewsets.GenericViewSet):
    serializer_class = TelemetrySerializer
    queryset = Telemetry.objects.select_related("device").all()
    pagination_class = TelemetryCursorPagination

    def create(self, request, *args, **kwargs):
        serializer = self.get_serializer(data=request.data)
        serializer.is_valid(raise_exception=True)
        telemetry = process_telemetry(serializer)
        return Response(self.get_serializer(telemetry).data, status=201)

# Read-only ViewSet for alerts.
# Alerts are generated by the server; clients can only list/retrieve them.
class AlertViewSet(viewsets.ReadOnlyModelViewSet):
    serializer_class = AlertSerializer
    queryset = Alert.objects.select_related("device").all()
    pagination_class = StandardCursorPagination

